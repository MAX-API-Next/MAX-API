func TestAstraPreservesOtherRequestFields(t *testing.T) {
	const payload = `{"model":"gpt-6-astra","messages":[{"role":"user","content":[{"type":"text","text":"Describe this"},{"type":"image_url","image_url":{"url":"https://example.com/image.png"}}]}],"max_completion_tokens":128,"reasoning_effort":"max","temperature":0.2,"top_p":0.8,"logprobs":true,"top_logprobs":5,"tools":[{"type":"function","function":{"name":"lookup","parameters":{"type":"object"}}}],"tool_choice":"auto","parallel_tool_calls":false,"seed":0}`
	var req dto.GeneralOpenAIRequest
	require.NoError(t, common.UnmarshalJsonStr(payload, &req))
	body, info := astraOutboundChat(t, &req, req.Model, constant.ChannelTypeOpenAI)
	for _, key := range []string{"messages", "tools", "tool_choice", "parallel_tool_calls", "seed", "max_completion_tokens", "reasoning_effort"} {
		require.JSONEq(t, gjson.Get(payload, key).Raw, gjson.GetBytes(body, key).Raw, key)
	}
	for _, key := range []string{"temperature", "top_p", "logprobs", "top_logprobs"} {
		require.False(t, gjson.GetBytes(body, key).Exists(), key)
	}
	require.Equal(t, "max", info.ReasoningEffort)
}

func TestAstraRespectsPreservedSuffix(t *testing.T) {
	settings := model_setting.GetGlobalSettings()
	before := settings.ThinkingModelBlacklist
	settings.ThinkingModelBlacklist = []string{"gpt-6-astra-high"}
	t.Cleanup(func() { settings.ThinkingModelBlacklist = before })
	req := &dto.GeneralOpenAIRequest{Model: "gpt-6-astra-high"}
	require.NoError(t, common.UnmarshalJsonStr(`{"max_tokens":16,"temperature":0.2}`, req))
	body, _ := astraOutboundChat(t, req, req.Model, constant.ChannelTypeOpenAI)
	require.Equal(t, "gpt-6-astra-high", gjson.GetBytes(body, "model").String())
	require.Equal(t, int64(16), gjson.GetBytes(body, "max_tokens").Int())
	require.Equal(t, 0.2, gjson.GetBytes(body, "temperature").Float())
	require.False(t, gjson.GetBytes(body, "reasoning_effort").Exists())
}

