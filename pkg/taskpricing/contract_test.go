type sample struct {
	ID         string                 `json:"id"`
	PluginKey  string                 `json:"plugin_key"`
	Models     []string               `json:"models"`
	Contract   types.TaskFactContract `json:"contract"`
	Expression string                 `json:"expression"`
	Submit     types.TaskPricingFacts `json:"submit"`
	Actual     types.TaskPricingFacts `json:"actual"`
	Expected   struct {
		SubmitUSD    float64 `json:"submit_usd"`
		FinalUSD     float64 `json:"final_usd"`
		QuotaPerUnit int     `json:"quota_per_unit"`
		GroupRatio   int     `json:"group_ratio"`
		Floor        int     `json:"floor"`
		Reserved     int     `json:"reserved"`
		Target       int     `json:"target"`
		Refund       int     `json:"refund"`
	} `json:"expected"`
}

func fixtures(t *testing.T) []sample {
	t.Helper()
	b, err := os.ReadFile("testdata/compat-v1.json")
	if err != nil {
		t.Fatal(err)
	}
	var f struct {
		Version  int      `json:"fixture_version"`
		Profiles []sample `json:"profiles"`
	}
	if err := common.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	if f.Version != 1 || len(f.Profiles) != 4 {
		t.Fatal("unexpected fixture scope")
	}
	return f.Profiles
}

// Run the shared production expression core. Expected amounts below remain
// independently derived rational numbers, never generated by the candidate.
func fixtureUSD(t *testing.T, expression string, facts types.TaskPricingFacts) float64 {
	t.Helper()
	quote, err := billingexpr.QuoteTaskExpression(billingexpr.TaskQuoteInput{
		Profile: billingexpr.TaskExpressionProfile, Expression: expression, Usage: facts,
		QuotaPerUnit: 1, GroupRatio: 1, PricingAt: time.Date(2026, 10, 29, 18, 0, 0, 0, time.UTC),
	})
	if err != nil {
		t.Fatal(err)
	}
	return quote.Amount
}

func TestThreeFamilyContractsAndIndependentAmounts(t *testing.T) {
	// Integer/rational oracle: H3 (40+30+2)/100; Kling 6/100;
	// Seedance 2M * 2/1M = 4. Group multiplier is applied exactly once.
	oracle := map[string][2]string{"hailuo-h3": {"102/100", "72/100"}, "kling-credit": {"1/10", "6/100"}, "seedance-1.5-audio": {"8", "4"}, "seedance-2-video": {"6", "4"}}
	for _, f := range fixtures(t) {
		t.Run(f.ID, func(t *testing.T) {
			frozen, err := SubmitFacts(f.Contract, f.Submit)
			if err != nil {
				t.Fatal(err)
			}
			final, err := CompleteFacts(f.Contract, frozen, f.Actual)
			if err != nil {
				t.Fatal(err)
			}
			want := oracle[f.ID]
			for i, facts := range []types.TaskPricingFacts{frozen, final} {
				r, ok := new(big.Rat).SetString(want[i])
				if !ok {
					t.Fatal("invalid oracle")
				}
				expected, _ := r.Float64()
				got := fixtureUSD(t, f.Expression, facts)
				fixtureExpected := []float64{f.Expected.SubmitUSD, f.Expected.FinalUSD}[i]
				if math.Abs(got-expected) > 1e-10 || fixtureExpected != expected {
					t.Fatalf("USD got %v, expected %v, fixture %v", got, expected, fixtureExpected)
				}
			}
			reserve := max(f.Expected.Floor, int(math.Round(fixtureUSD(t, f.Expression, frozen)*float64(f.Expected.QuotaPerUnit*f.Expected.GroupRatio))))
			target := int(math.Round(fixtureUSD(t, f.Expression, final) * float64(f.Expected.QuotaPerUnit*f.Expected.GroupRatio)))
			if reserve != f.Expected.Reserved || target != f.Expected.Target || reserve-target != f.Expected.Refund {
				t.Fatal("fixture reservation/target/refund mismatch")
			}
			// Alias changes to caller-owned maps cannot mutate the frozen scalar facts.
			for key := range f.Submit {
				f.Submit[key] = nil
			}
			if _, err := CompleteFacts(f.Contract, frozen, f.Actual); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestPresenceAndFrozenFacts(t *testing.T) {
	for _, f := range fixtures(t) {
		t.Run(f.ID, func(t *testing.T) {
			frozen, err := SubmitFacts(f.Contract, f.Submit)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := CompleteFacts(f.Contract, frozen, nil); err == nil {
				t.Fatal("submit estimate accepted as final actual")
			}
			for key, policy := range f.Contract.FieldPolicy {
				if policy.Phase != "actual" {
					continue
				}
				for _, value := range []any{nil, "0", -1, math.NaN(), math.Inf(1), math.Exp2(53), []int{0}, true} {
					bad := copyFacts(f.Actual)
					bad[key] = value
					if _, err := CompleteFacts(f.Contract, frozen, bad); err == nil {
						t.Fatalf("accepted %s=%v", key, value)
					}
				}
			}
			bad := copyFacts(f.Actual)
			bad["legacy_extra"] = 1
			if _, err := CompleteFacts(f.Contract, frozen, bad); err == nil {
				t.Fatal("undeclared fact accepted")
			}
			if f.ID == "kling-credit" {
				zero, err := CompleteFacts(f.Contract, frozen, types.TaskPricingFacts{"units": 0})
				if err != nil || zero["units"] != float64(0) {
					t.Fatal("explicit credit zero lost", err)
				}
				if target := fixtureUSD(t, f.Expression, zero); target != 0 {
					t.Fatal("zero target changed")
				}
				// 0.005 credit * $0.1 * 1000 = 0.5 quota -> round half up to 1.
				half, err := CompleteFacts(f.Contract, frozen, types.TaskPricingFacts{"units": .005})
				if err != nil {
					t.Fatal(err)
				}
				if math.Round(fixtureUSD(t, f.Expression, half)*1000) != 1 {
					t.Fatal("half quota rounding")
				}
			}
			if f.ID == "seedance-1.5-audio" {
				final, err := CompleteFacts(f.Contract, frozen, f.Actual)
				if err != nil || final["generate_audio"] != false {
					t.Fatal("false not inherited", err)
				}
				bad := copyFacts(f.Actual)
				bad["generate_audio"] = true
				if _, err := CompleteFacts(f.Contract, frozen, bad); err == nil {
					t.Fatal("frozen request altered")
				}
				delete(f.Submit, "generate_audio")
				if _, err := SubmitFacts(f.Contract, f.Submit); err == nil {
					t.Fatal("missing boolean became false")
				}
			}
		})
	}
}

func copyFacts(f types.TaskPricingFacts) types.TaskPricingFacts {
	out := types.TaskPricingFacts{}
	for k, v := range f {
		out[k] = v
	}
	return out
}

func TestContractDigestAndModelBoundaries(t *testing.T) {
	for _, f := range fixtures(t) {
		before, err := ContractDigest(f.Contract)
		if err != nil {
			t.Fatal(err)
		}
		normalized, err := NormalizeContract(f.Contract)
		if err != nil {
			t.Fatal(err)
		}
		for key, field := range normalized.UsageSchema {
			field.Description = map[string]string{"en": "cosmetic only"}
			slices.Reverse(field.Enum)
			normalized.UsageSchema[key] = field
		}
		after, err := ContractDigest(normalized)
		if err != nil || before != after {
			t.Fatal("cosmetic digest changed", err)
		}
		for key, field := range normalized.UsageSchema {
			changed, _ := NormalizeContract(f.Contract)
			if field.Type == "number" {
				field.Unit = "credit"
				if f.Contract.UsageSchema[key].Unit == "credit" {
					field.Unit = "token"
				}
			} else if len(field.Enum) > 0 {
				field.Enum = append(field.Enum, "new-value")
			} else {
				continue
			}
			changed.UsageSchema[key] = field
			digest, err := ContractDigest(changed)
			if err != nil || digest == before {
				t.Fatal("semantic drift undetected", err)
			}
		}
	}
	f := fixtures(t)
	if slices.Contains(f[1].Models, "kling-v3") {
		t.Fatal("unsupported upstream Kling claimed")
	}
	if _, err := SubmitFacts(f[2].Contract, types.TaskPricingFacts{"tokens": 1, "resolution": "4k", "generate_audio": false}); err == nil {
		t.Fatal("Seedance 2 schema leaked into 1.5")
	}
	if _, err := SubmitFacts(f[3].Contract, types.TaskPricingFacts{"tokens": 1, "resolution": "4k", "video_input": "video", "generate_audio": true}); err == nil {
		t.Fatal("Seedance 1.5 schema leaked into 2")
	}
}

func TestPricingChangeWirePresence(t *testing.T) {
	b, err := os.ReadFile("testdata/compat-v1.json")
	if err != nil {
		t.Fatal(err)
	}
	var f struct {
		Changes []types.ModelPricingChange `json:"patch_cases"`
	}
	if err := common.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	for i, change := range f.Changes {
		wire, err := common.Marshal(change)
		if err != nil {
			t.Fatal(err)
		}
		var roundtrip types.ModelPricingChange
		if err := common.Unmarshal(wire, &roundtrip); err != nil || !reflect.DeepEqual(change, roundtrip) {
			t.Fatal("PATCH wire changed", err)
		}
		if (i == 0 && (change.Reset == nil || *change.Reset)) || (i == 1 && change.Reset != nil) {
			t.Fatal("reset false/missing collapsed")
		}
		parsed, err := DecodePricingChange(wire)
		if err != nil || !reflect.DeepEqual(change, parsed) {
			t.Fatal("PATCH boundary changed", err)
		}
		if i == 0 && change.Pricing["ModelPrice"] != float64(0) {
			t.Fatal("explicit free price lost")
		}
		if i == 1 {
			if _, exists := change.Pricing["ModelPrice"]; exists {
				t.Fatal("missing price became free")
			}
		}
	}
	for _, wire := range []string{
		`{"model_name":"kling-v1","expected_version":"v1","pricing":{},"reset":null}`,
		`{"model_name":"kling-v1","expected_version":"v1","pricing":{},"extra":1}`,
		`{"model_name":"kling-v1","pricing":{}}`,
		`{"model_name":"kling-v1","expected_version":"v1","pricing":null}`,
	} {
		if _, err := DecodePricingChange([]byte(wire)); err == nil {
			t.Fatal("invalid PATCH shape accepted", wire)
		}
	}
}

func TestInvalidContractsAndNumericBounds(t *testing.T) {
	f := fixtures(t)[1]
	for _, mutate := range []func(*types.TaskFactContract){
		func(c *types.TaskFactContract) { c.Version = 2 },
		func(c *types.TaskFactContract) {
			p := c.FieldPolicy["units"]
			p.Phase = "live"
			c.FieldPolicy["units"] = p
		},
		func(c *types.TaskFactContract) { delete(c.FieldPolicy, "units") },
		func(c *types.TaskFactContract) {
			f := c.UsageSchema["units"]
			f.Unit = "millisecond"
			c.UsageSchema["units"] = f
		},
		func(c *types.TaskFactContract) {
			p := c.FieldPolicy["units"]
			v := -1.
			p.Min = &v
			c.FieldPolicy["units"] = p
		},
	} {
		c, err := NormalizeContract(f.Contract)
		if err != nil {
			t.Fatal(err)
		}
		mutate(&c)
		if _, err := ContractDigest(c); err == nil {
			t.Fatal("invalid contract accepted")
		}
	}
	for _, index := range []int{0, 2} {
		f := fixtures(t)[index]
		key := "seconds"
		if index == 2 {
			key = "tokens"
		}
		for _, v := range []float64{0, 1e12} {
			bad := copyFacts(f.Actual)
			bad[key] = v
			if _, err := CompleteFacts(f.Contract, f.Submit, bad); err == nil {
				t.Fatal("range accepted", f.ID, v)
			}
		}
	}
}
